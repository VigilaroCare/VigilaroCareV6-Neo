/**
 * Retorna a orientação de curto/médio/longo prazo para um item pendente.
 * Casa pela primeira tag do item que exista no dicionário; sem match,
 * cai no fallback por gravidade (isCritical).
 * @param {{ tags?: string[], isCritical?: boolean }} item
 */
export function getPendingGuidance(item) {
    const tags = item?.tags || [];
    for (const tag of tags) {
        if (TAG_GUIDANCE[tag]) return TAG_GUIDANCE[tag];
    }
    return item?.isCritical ? FALLBACK_CRITICAL : FALLBACK_ATTENTION;
}
